type LoginRequest struct {
	Identifier string `json:"identifier" validate:"required"`
	Password   string `json:"password"   validate:"required"`
}

// loginIdentifier returns the display value for audit logs (email or TIN).
func (r *LoginRequest) loginIdentifier() string { return r.Identifier }

type LoginResponse struct {
	AccessToken  string `json:"access_token"`
	RefreshToken string `json:"refresh_token"`
}

type RefreshTokenRequest struct {
	RefreshToken string `json:"refresh_token" validate:"required"`
}

type RefreshTokenResponse struct {
	AccessToken  string `json:"access_token"`
	RefreshToken string `json:"refresh_token"`
}

type ChangePasswordRequest struct {
	CurrentPassword string `json:"current_password"`
	NewPassword     string `json:"new_password"`
}

type VerifyPasswordRequest struct {
	Password string `json:"password" validate:"required"`
}

// LoginResponseExtended includes additional security info
type LoginResponseExtended struct {
	AccessToken        string `json:"access_token,omitempty"`
	RefreshToken       string `json:"refresh_token,omitempty"`
	Requires2FA        bool   `json:"requires_2fa,omitempty"`
	TwoFactorMethod    string `json:"two_factor_method,omitempty"`
	SessionToken       string `json:"session_token,omitempty"`
	MustChangePassword bool   `json:"must_change_password,omitempty"`
}

